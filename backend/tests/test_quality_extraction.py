FOOTER = "Digitized legal document - generated by office export system"


@pytest.fixture(autouse=True)
def extraction_settings(monkeypatch):
    monkeypatch.setattr(settings, "ocr_enabled", True)
    monkeypatch.setattr(settings, "ocr_threads", 1)
    monkeypatch.setattr(settings, "ocr_dpi", 72)
    monkeypatch.setattr(settings, "ocr_min_text_chars", 40)


def make_pdf(tmp_path, *, image_rect=(0, 0, 595, 800), native_text=FOOTER, hidden_text=False):
    image = Image.new("RGB", (160, 200), "white")
    ImageDraw.Draw(image).text((10, 20), "Scanned contract", fill="black")
    stream = io.BytesIO()
    image.save(stream, format="PNG")
    path = tmp_path / "hybrid.pdf"
    with pymupdf.open() as pdf:
        page = pdf.new_page(width=595, height=842)
        page.insert_image(pymupdf.Rect(image_rect), stream=stream.getvalue(), keep_proportion=False)
        if len(native_text) < 200:
            page.insert_text((25, 820), native_text, fontsize=9, render_mode=3 if hidden_text else 0)
        else:
            space = page.insert_textbox(pymupdf.Rect(25, 35, 570, 780), native_text, fontsize=9,
                                       render_mode=3 if hidden_text else 0)
            assert space >= 0, "Synthetic PDF must contain the intended text layer"
        pdf.save(path)
    return path


def tesseract_data(words, confidences):
    size = len(words)
    return dict(
        text=words, conf=confidences,
        block_num=[1] * size, par_num=[1] * size, line_num=[1] * size,
        left=[10 + i * 30 for i in range(size)], top=[10] * size,
        width=[25] * size, height=[12] * size,
    )


def test_large_scanned_page_with_native_footer_is_ocr_and_text_is_not_duplicated(tmp_path, monkeypatch):
    source = make_pdf(tmp_path)
    recognize = Mock(return_value=tesseract_data(["Scanned", "terms", FOOTER], [95, 95, 95]))
    monkeypatch.setattr(pytesseract, "image_to_data", recognize)

    pages = extraction.extract_pages(source)

    assert len(pages) == 1 and pages[0].is_ocr
    assert recognize.call_count == 1
    assert "Scanned terms" in pages[0].text
    assert pages[0].text.count(FOOTER) == 1
    assert pages[0].ocr_error is None
    quality = build_quality_snapshot(pages, 80)
    assert quality["ocr_pages"] == 1 and quality["native_pages"] == 0


@pytest.mark.parametrize("image_rect", [(25, 25, 100, 100), (300, 600, 420, 720)])
def test_small_logo_or_stamp_does_not_force_ocr_of_native_text(tmp_path, monkeypatch, image_rect):
    source = make_pdf(tmp_path, image_rect=image_rect)
    recognize = Mock(side_effect=AssertionError("Text with a small logo must be read directly"))
    monkeypatch.setattr(pytesseract, "image_to_data", recognize)

    pages = extraction.extract_pages(source)

    assert not pages[0].is_ocr and pages[0].text == FOOTER
    assert pages[0].ocr_confidence is None
    recognize.assert_not_called()


@pytest.mark.parametrize("hidden_text", [False, True])
def test_substantial_native_or_existing_hidden_ocr_layer_is_preserved(tmp_path, monkeypatch, hidden_text):
    text = "Payment must be made within thirty days after delivery of all goods.\n" * 12
    source = make_pdf(tmp_path, native_text=text, hidden_text=hidden_text)
    recognize = Mock(side_effect=AssertionError("Do not OCR a substantial existing text layer again"))
    monkeypatch.setattr(pytesseract, "image_to_data", recognize)

    pages = extraction.extract_pages(source)

    assert len(pages[0].text) > 200 and not pages[0].is_ocr
    assert pages[0].ocr_confidence is None
    assert "Payment must be made" in pages[0].text
    recognize.assert_not_called()


def test_off_page_image_area_is_not_counted_as_scanned_page_coverage(tmp_path, monkeypatch):
    source = make_pdf(tmp_path, image_rect=(-500, 0, 70, 800))
    recognize = Mock(side_effect=AssertionError("Only a narrow visible image strip is on this page"))
    monkeypatch.setattr(pytesseract, "image_to_data", recognize)

    pages = extraction.extract_pages(source)

    assert not pages[0].is_ocr
    recognize.assert_not_called()


def test_disabled_ocr_does_not_label_a_scanned_page_as_native(tmp_path, monkeypatch):
    source = make_pdf(tmp_path)
    monkeypatch.setattr(settings, "ocr_enabled", False)
    recognize = Mock(side_effect=AssertionError("OCR is disabled"))
    monkeypatch.setattr(pytesseract, "image_to_data", recognize)

    pages = extraction.extract_pages(source)

    assert pages[0].is_ocr and pages[0].ocr_error == "ocr_disabled"
    assert pages[0].text == FOOTER and pages[0].ocr_confidence is None
    quality = build_quality_snapshot(pages, 80)
    assert quality["ocr_percent"] == 100 and quality["manual_review_required"]
    assert quality["review_pages"][0]["reason"] == "ocr_disabled"
    recognize.assert_not_called()


@pytest.mark.parametrize("failure", ["ocr", "render"])
def test_failed_page_keeps_diagnostics_and_native_footer(tmp_path, monkeypatch, failure):
    source = make_pdf(tmp_path)
    if failure == "ocr":
        monkeypatch.setattr(pytesseract, "image_to_data", Mock(side_effect=RuntimeError("OCR unavailable")))
    else:
        monkeypatch.setattr(extraction, "_render", Mock(side_effect=RuntimeError("Cannot render page")))
    progress = []

    pages = extraction.extract_pages(source, on_page=lambda done, total: progress.append((done, total)))

    assert pages[0].is_ocr and pages[0].ocr_error == "ocr_failed"
    assert pages[0].text == FOOTER and pages[0].ocr_confidence is None
    quality = build_quality_snapshot(pages, 80)
    assert quality["ocr_percent"] == 100 and quality["manual_review_required"]
    assert quality["review_pages"][0]["reason"] == "ocr_failed"
    assert progress[-1] == (1, 1)


def test_empty_tesseract_output_is_an_unknown_image_page(tmp_path, monkeypatch):
    source = make_pdf(tmp_path)
    monkeypatch.setattr(pytesseract, "image_to_data", Mock(return_value=tesseract_data([""], [-1])))

    pages = extraction.extract_pages(source)

    assert pages[0].is_ocr and pages[0].ocr_error == "ocr_empty"
    assert pages[0].text == "" and pages[0].ocr_confidence is None
    quality = build_quality_snapshot(pages, 80)
    assert quality["status"] == "unknown" and quality["manual_review_required"]


def test_tesseract_confidence_is_compared_before_rounding(monkeypatch):
    monkeypatch.setattr(pytesseract, "image_to_data", Mock(return_value=tesseract_data(["Payment"], [79.96])))

    page = extraction.ocr_image(Image.new("L", (200, 200), 255), 1, 595, 842)
    quality = build_quality_snapshot([page], 80)

    assert page.ocr_confidence == pytest.approx(79.96)
    assert quality["status"] == "low" and quality["manual_review_required"]
    assert quality["review_pages"][0]["confidence"] < 80


def test_tesseract_minus_one_is_not_a_word_but_zero_is_valid_confidence(monkeypatch):
    data = tesseract_data(["noise", "Payment", "terms", " ", "bad", "invalid"], [-1, 0, 80, 100, float("nan"), 101])
    monkeypatch.setattr(pytesseract, "image_to_data", Mock(return_value=data))

    page = extraction.ocr_image(Image.new("L", (200, 200), 255), 1, 595, 842)

    assert page.text == "Payment terms"
    assert page.ocr_confidence == 40 and page.ocr_error is None
    assert len(page.words) == 2


def test_real_tesseract_reads_scanned_terms_even_when_native_footer_is_present(tmp_path, monkeypatch):
    if not shutil.which("tesseract"):
        pytest.skip("Tesseract is unavailable")
    if "eng" not in pytesseract.get_languages():
        pytest.skip("English Tesseract data is unavailable")
    font_path = Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
    if not font_path.is_file():
        pytest.skip("Fixture font is unavailable")
    monkeypatch.setattr(settings, "ocr_languages", "eng")
    monkeypatch.setattr(settings, "ocr_dpi", 150)
    image = Image.new("RGB", (1190, 1600), "white")
    draw = ImageDraw.Draw(image)
    font = ImageFont.truetype(str(font_path), 36)
    for index, line in enumerate([
        "CONTRACT TERMS",
        "Payment is due within thirty days.",
        "Delivery is required before November.",
        "All goods must meet the specification.",
    ]):
        draw.text((80, 120 + 70 * index), line, fill="black", font=font)
    stream = io.BytesIO()
    image.save(stream, format="PNG")
    source = tmp_path / "actual_scan.pdf"
    with pymupdf.open() as pdf:
        page = pdf.new_page(width=595, height=842)
        page.insert_image(pymupdf.Rect(0, 0, 595, 800), stream=stream.getvalue())
        page.insert_text((25, 820), FOOTER, fontsize=9)
        pdf.save(source)

    pages = extraction.extract_pages(source)

    assert pages[0].is_ocr and pages[0].ocr_error is None
    assert "Payment" in pages[0].text and "Delivery" in pages[0].text
    assert pages[0].ocr_confidence is not None
